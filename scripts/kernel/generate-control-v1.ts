// Offline source generation only. These hashes are not installed-image,
// StateOwner, peer, permission or runtime-integrity evidence.
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';
import { canonicalSha256 } from '../../src/kernel/canonical.js';

const repository = fileURLToPath(new URL('../../', import.meta.url));
const entry = 'src/kernel/control-wire.ts';
const stableFields = ['dev', 'ino', 'mode', 'uid', 'gid', 'nlink', 'size', 'mtimeNs', 'ctimeNs'] as const;

function sourceBytes(filename: string): Buffer {
  const fd = fs.openSync(filename, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
  try {
    const before = fs.fstatSync(fd, { bigint: true });
    assert(before.isFile() && before.nlink === 1n && before.size <= 1024n * 1024n);
    const bytes = fs.readFileSync(fd);
    assert.equal(BigInt(bytes.length), before.size);
    for (const after of [fs.fstatSync(fd, { bigint: true }), fs.lstatSync(filename, { bigint: true })])
      for (const field of stableFields) assert.equal(before[field], after[field]);
    return bytes;
  } finally { fs.closeSync(fd); }
}

/** All statically named local TypeScript dependencies, including type-only
 * imports, reexports, import types and literal dynamic imports. External
 * module names are declared, not claimed to be source-frozen by this digest. */
export function controlSourceManifest(root = repository) {
  const queue = [entry], sources = new Map<string, string>(), externals = new Set<string>();
  let totalBytes = 0;
  while (queue.length) {
    const name = queue.shift()!;
    if (sources.has(name)) continue;
    assert(sources.size < 1000);
    const filename = path.resolve(root, name);
    assert(filename.startsWith(path.resolve(root, 'src') + path.sep));
    const bytes = sourceBytes(filename); totalBytes += bytes.length; assert(totalBytes <= 16 * 1024 * 1024);
    sources.set(name, crypto.createHash('sha256').update(bytes).digest('hex'));
    const parsed = ts.createSourceFile(name, new TextDecoder('utf-8', { fatal: true }).decode(bytes), ts.ScriptTarget.Latest, true);
    const imports: string[] = [];
    const visit = (node: ts.Node): void => {
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
        assert(ts.isStringLiteral(node.moduleSpecifier)); imports.push(node.moduleSpecifier.text);
      } else if (ts.isImportTypeNode(node)) {
        assert(ts.isLiteralTypeNode(node.argument) && ts.isStringLiteral(node.argument.literal));
        imports.push(node.argument.literal.text);
      } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
        assert(node.arguments.length === 1 && ts.isStringLiteral(node.arguments[0]!));
        imports.push((node.arguments[0] as ts.StringLiteral).text);
      }
      ts.forEachChild(node, visit);
    };
    visit(parsed);
    for (const specifier of imports) {
      if (!specifier.startsWith('.')) { externals.add(specifier); continue; }
      assert(!specifier.includes('\\') && !specifier.includes('\0') && specifier.endsWith('.js'));
      const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(name), specifier.slice(0, -3) + '.ts'));
      assert(dependency.startsWith('src/') && !dependency.split('/').includes('..'));
      queue.push(dependency);
    }
  }
  return Object.freeze({ entry, scope: 'static_local_typescript_dependency_closure_including_types' as const,
    sources: Object.freeze(Object.fromEntries([...sources].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))),
    externalImports: Object.freeze([...externals].sort()) });
}

export function renderControlV1(root = repository): string {
  const manifest = controlSourceManifest(root);
  return `// Generated by scripts/kernel/generate-control-v1.ts. Do not edit.\n` +
    `// Executable schemas delegate to canonical codecs; this is not full v1\n` +
    `// method implementation or runtime/authority evidence.\n` +
    `export { CONTROL_FRAME_BYTES, CONTROL_METHODS_V1, INSTALLED_CONTROL_FEATURES, CONTROL_PROTOCOL_VERSION, HEADLESS_SCHEMA_VERSION,\n` +
    `  decodeControlFrame, decodeInstalledControlRequest, decodeInstalledControlEnvelope,\n` +
    `  decodeInstalledControlResponse, decodeHeadlessControlRequest, decodeHeadlessControlResponse, decodeHeadlessControlRecord, headlessControlResponse, headlessControlHello, headlessRunEvent } from '../kernel/control-wire.js';\n` +
    `export type { InstalledControlFeature, InstalledControlMethod, InstalledControlRequestV1,\n` +
    `  InstalledControlResponseFor, InstalledControlResultFor, HeadlessControlRequestV3, HeadlessControlResponseV3, HeadlessRunEventV3, HeadlessControlRecordV3 } from '../kernel/control-wire.js';\n\n` +
    `export const CONTROL_V1_SOURCE_DIGEST = ${JSON.stringify(canonicalSha256(manifest))};\n` +
    `export const CONTROL_V1_SOURCE_MANIFEST = Object.freeze({\n` +
    `  entry: ${JSON.stringify(manifest.entry)},\n  scope: ${JSON.stringify(manifest.scope)},\n` +
    `  sources: Object.freeze(${JSON.stringify(manifest.sources, null, 2)}),\n` +
    `  externalImports: Object.freeze(${JSON.stringify(manifest.externalImports)})\n});\n` +
    `export { CONTROL_METHODS_V1 as CONTROL_V1_DECLARED_METHOD_METADATA,\n` +
    `  INSTALLED_CONTROL_FEATURES as CONTROL_V1_CONNECTED_METHOD_METADATA } from '../kernel/control-wire.js';\n`;
}

export function checkControlV1(root = repository): void {
  if (!sourceBytes(path.join(root, 'src/control/v1.ts')).equals(Buffer.from(renderControlV1(root))))
    throw new Error('generated_control_v1_is_stale');
}

async function main(): Promise<void> {
  const args = process.argv.slice(2); assert(args.length === 1 && ['--check', '--print', '--write'].includes(args[0]!));
  if (args[0] === '--check') { checkControlV1(); return; }
  const generated = renderControlV1(), target = path.join(repository, 'src/control/v1.ts');
  if (args[0] === '--print') process.stdout.write(generated);
  else fs.writeFileSync(target, generated);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href)
  await main().catch(() => { process.stderr.write('generated_control_v1_check_failed\n'); process.exitCode = 1; });
